export function serviceIcon(name: string) {
  const n = name.toLowerCase();
  if (/unha|manicure|pedicure|esmalt|gel/.test(n)) return "hand";
  if (/barba|bigode/.test(n)) return "smile";
  if (/maqui|make/.test(n)) return "brush";
  if (/sobrancelha|cílio|cilio|lash/.test(n)) return "eye";
  if (/massag|depila|spa|limpeza|pele|facial/.test(n)) return "sparkles";
  if (/escova|chapinha|hidrat|progressiva|selagem/.test(n)) return "wind";
  if (/corte|cabelo|franja/.test(n)) return "scissors";
  if (/colora|tintura|luzes|mecha|balayage|loiro|tonal/.test(n)) return "palette";
  return "sparkles";
}

